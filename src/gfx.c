UINT32 make_color_gop(EFI_GRAPHICS_OUTPUT_PROTOCOL *gop, UINT8 r, UINT8 g, UINT8 b) {
  if (gop && gop->Mode && gop->Mode->Info && gop->Mode->Info->PixelFormat == PIXEL_RGB_RESERVED_8BIT_PER_COLOR) {
    return (UINT32)r | ((UINT32)g << 8) | ((UINT32)b << 16);
  }
  return (UINT32)b | ((UINT32)g << 8) | ((UINT32)r << 16);
}

void fb_pixel(UINT32 *fb, UINT32 stride, UINT32 w, UINT32 h, int x, int y, UINT32 color) {
  if (x >= 0 && (UINT32)x < w && y >= 0 && (UINT32)y < h) {
    fb[(UINT32)y * stride + (UINT32)x] = color;
  }
}

void fb_fill_rect(UINT32 *fb, UINT32 stride, UINT32 w, UINT32 h, int rx, int ry, int rw, int rh, UINT32 color) {
  int x, y;
  int x2 = rx + rw;
  int y2 = ry + rh;
  if (rx < 0) rx = 0;
  if (ry < 0) ry = 0;
  if (x2 > (int)w) x2 = (int)w;
  if (y2 > (int)h) y2 = (int)h;

  for (y = ry; y < y2; y++) {
    UINT32 *row = &fb[(UINT32)y * stride];
    for (x = rx; x < x2; x++) {
      row[x] = color;
    }
  }
}

void fb_draw_rect(UINT32 *fb, UINT32 stride, UINT32 w, UINT32 h, int rx, int ry, int rw, int rh, int border, UINT32 color) {
  fb_fill_rect(fb, stride, w, h, rx, ry, rw, border, color);
  fb_fill_rect(fb, stride, w, h, rx, ry + rh - border, rw, border, color);
  fb_fill_rect(fb, stride, w, h, rx, ry, border, rh, color);
  fb_fill_rect(fb, stride, w, h, rx + rw - border, ry, border, rh, color);
}

void fb_draw_char(UINT32 *fb, UINT32 stride, UINT32 w, UINT32 h, int x, int y, char c, int scale, UINT32 fg, UINT32 bg, int draw_bg) {
  int idx = (int)(UINT8)c - 32;
  if (idx < 0 || idx >= 95) idx = 0;
  const UINT8 *glyph = font8x16[idx];
  int row, col, sx, sy;

  for (row = 0; row < 16; row++) {
    UINT8 bits = glyph[row];
    for (col = 0; col < 8; col++) {
      int pixel_set = (bits & (0x80 >> col)) != 0;
      UINT32 color = pixel_set ? fg : bg;
      if (pixel_set || draw_bg) {
        for (sy = 0; sy < scale; sy++) {
          for (sx = 0; sx < scale; sx++) {
            fb_pixel(fb, stride, w, h, x + col * scale + sx, y + row * scale + sy, color);
          }
        }
      }
    }
  }
}

void fb_draw_text(UINT32 *fb, UINT32 stride, UINT32 w, UINT32 h, int x, int y, const char *text, int scale, UINT32 fg, UINT32 bg, int draw_bg) {
  int cx = x;
  while (*text) {
    if (*text == '\n') {
      cx = x;
      y += 16 * scale;
    } else {
      fb_draw_char(fb, stride, w, h, cx, y, *text, scale, fg, bg, draw_bg);
      cx += 8 * scale;
    }
    text++;
  }
}

